/// Fallback glyph for a character not present in the block font.
pub fn fallback() -> [u8; 7] {
    [
        0b11111, 0b10001, 0b10101, 0b10101, 0b10101, 0b10001, 0b11111,
    ]
}

pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;
pub const ADVANCE: f32 = 6.0;

/// Layout text into (glyph, x, y, coverage_bits) in font units.
pub fn layout(text: &str) -> Vec<(char, f32, [u8; 7])> {
    let mut out = Vec::new();
    let mut x = 0.0f32;
    let mut y = 0.0f32;
    for c in text.chars() {
        if c == '\n' {
            x = 0.0;
            y += GLYPH_H as f32 + 2.0;
            continue;
        }
        let g = glyph(c).unwrap_or_else(fallback);
        out.push((c, x, g));
        x += ADVANCE;
    }
    // Encode y in the returned tuple's second element's fractional part is not
    // needed for single-line; multiline handled by grouping in the caller.
    out
}

/// Measure text in font units.
pub fn measure(text: &str) -> (f32, f32) {
    let mut w = 0.0f32;
    let mut maxw = 0.0f32;
    let mut lines = 1.0f32;
    for c in text.chars() {
        if c == '\n' {
            maxw = maxw.max(w);
            w = 0.0;
            lines += 1.0;
        } else {
            w += ADVANCE;
        }
    }
    maxw = maxw.max(w);
    (maxw, lines * (GLYPH_H as f32 + 2.0))
}
